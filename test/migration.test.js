'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const http = require('node:http');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { createEngineServer } = require('../src/server');
const AtomicFile = require('../src/runtime/atomic-file');

test('paused ownership migration retains baseline and resumes frozen claim without repeating completed history', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'engine-cutover-'));
  const sourceDataDir = path.join(root, 'old-shell');
  const repoPath = path.join(root, '代码 空格'); const knowledgePath = path.join(root, '知识');
  fs.mkdirSync(repoPath); fs.mkdirSync(knowledgePath);
  const git = args => execFileSync('git', args, { cwd: repoPath, windowsHide: true, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git(['init', '-q']); git(['config', 'user.email', 'test@local.invalid']); git(['config', 'user.name', 'Cutover Test']);
  fs.writeFileSync(path.join(repoPath, 'file.txt'), 'baseline'); git(['add', '.']); git(['commit', '-qm', 'baseline']);
  const baseline = git(['rev-parse', 'HEAD']);
  fs.writeFileSync(path.join(repoPath, 'file.txt'), 'pending'); git(['add', '.']); git(['commit', '-qm', 'pending']);
  const commitSha = git(['rev-parse', 'HEAD']);
  fs.writeFileSync(path.join(knowledgePath, 'README.md'), '# Keep existing knowledge\n');
  const registration = { projectId: 'project-old', repoPath, knowledgePath, trackingStartCommit: baseline };
  const old = createEngineServer({ dataDir: sourceDataDir, managed: true }); await old.ready;
  old.coordinator.layout.getProjectMetadataDir = id => path.join(sourceDataDir, 'projects', id);
  old.store.addProject(registration);
  await old.coordinator.reconciler.prepareClaim(registration.projectId, 'git-hook', 'op-frozen-migration', old.store.getProject(registration.projectId), '', commitSha);
  const runtime = old.store.readRuntime(registration.projectId);
  const oldFingerprint = runtime.analysis.activeClaim.fingerprint;
  const migrationId = `cutover-${crypto.randomUUID()}`;
  const backup = path.join(sourceDataDir, 'recovery', 'engine-cutover', migrationId);
  fs.mkdirSync(backup, { recursive: true });
  for (const kind of ['runtime', 'projects']) if (fs.existsSync(path.join(sourceDataDir, kind))) fs.cpSync(path.join(sourceDataDir, kind), path.join(backup, kind), { recursive: true });
  const snapshot = { migrationId, sourceDataDir, projects: [{ registration, runtime }] };
  AtomicFile.writeJsonAtomic(path.join(backup, 'snapshot.json'), snapshot);
  let analyses = 0;
  const vector = http.createServer((req, res) => { res.setHeader('Content-Type', 'application/json'); res.end('{"ok":true}'); });
  await new Promise(resolve => vector.listen(0, '127.0.0.1', resolve));
  const engine = createEngineServer({ dataDir: path.join(root, 'engine'), managed: true, runtimeToken: 'cutover-token', vectorUrl: `http://127.0.0.1:${vector.address().port}`, bridge: { async registerConsumer() {}, async listJournals() { return []; } }, analyzer: { async runClaim(input) {
    analyses++;
    assert.equal(input.claim.fingerprint, oldFingerprint);
    assert.ok(input.evidence.evidenceBundle.root.startsWith(path.join(root, 'engine')));
    const content = `# Migrated commit\n\n${input.claim.commitSha}`;
    AtomicFile.writeFileAtomic(path.join(input.stagingPath, 'files', 'changes', 'migrated.md'), content);
    AtomicFile.writeJsonAtomic(input.manifestPath, { schema: 'knowledge-staging-manifest/v1', projectId: input.projectId, runId: input.claim.runId, commitSha: input.claim.commitSha, operations: [{ path: 'changes/migrated.md', operation: 'create', reason: 'Recovered frozen evidence', sha256: `sha256:${crypto.createHash('sha256').update(content).digest('hex')}`, evidenceReferences: [`commit:${commitSha}`, `patch:${input.claim.patchHash}`, `conversation:${input.claim.conversationSnapshotHash}`, `retrieval:${input.claim.retrievalManifestHash}`] }] });
  } } });
  await engine.ready; await new Promise(resolve => engine.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await engine.close(); old.coordinator.close(); vector.closeAllConnections(); await new Promise(resolve => vector.close(resolve)); });
  const base = `http://127.0.0.1:${engine.server.address().port}`;
  const post = (route, body, headers = {}) => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer cutover-token', ...headers }, body: JSON.stringify(body) });
  assert.equal((await post('/api/control', { enabled: true }, { Origin: base })).status, 403);
  assert.equal((await post('/api/migrate', snapshot)).status, 200);
  assert.equal((await post('/api/migrate', snapshot)).status, 200);
  assert.equal(analyses, 0, 'migration must not dispatch while paused');
  assert.equal(engine.store.readRuntime('project-old').lastAnalyzedCommit, baseline);
  assert.equal((await post('/api/control', { enabled: true })).status, 200);
  for (let i = 0; i < 200 && !engine.store.state.runs.every(r => ['succeeded', 'failed'].includes(r.state)); i++) await new Promise(resolve => setTimeout(resolve, 20));
  assert.equal(engine.store.state.runs[0].state, 'succeeded', JSON.stringify(engine.store.state.runs[0].error));
  assert.equal(analyses, 1);
  assert.equal(engine.store.readRuntime('project-old').lastAnalyzedCommit, commitSha);
  assert.equal(fs.readFileSync(path.join(knowledgePath, 'README.md'), 'utf8'), '# Keep existing knowledge\n');
  assert.equal(fs.existsSync(path.join(backup, 'snapshot.json')), true);
  assert.equal(old.store.readRuntime('project-old').lastAnalyzedCommit, baseline, 'old executor state must remain untouched');
});
